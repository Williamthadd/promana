test('final verification rejects altered SHA-256 metadata and MIME declarations', async () => {
  const transfer = await prepareOpticalTransfer({
    bytes: makeImageBytes('image/png', 1_001),
    filename: 'integrity.png',
    mimeType: 'image/png',
    sessionId: fixedSession(),
  })

  const badHashMetadata = transfer.metadataPacket.slice()
  badHashMetadata[37] ^= 0xff
  rewriteChecksum(badHashMetadata)
  const hashCollector = createOpticalTransferCollector()
  hashCollector.ingestPacket(badHashMetadata)
  for (const packet of transfer.dataPackets) {
    hashCollector.ingestPacket(packet)
  }
  await assert.rejects(
    hashCollector.assembleAndVerify(),
    expectProtocolCode('SHA256_MISMATCH'),
  )

  const jpegDeclaredMetadata = transfer.metadataPacket.slice()
  jpegDeclaredMetadata[34] = 2
  rewriteChecksum(jpegDeclaredMetadata)
  const mimeCollector = createOpticalTransferCollector()
  mimeCollector.ingestPacket(jpegDeclaredMetadata)
  for (const packet of transfer.dataPackets) {
    mimeCollector.ingestPacket(packet)
  }
  await assert.rejects(
    mimeCollector.assembleAndVerify(),
    expectProtocolCode('MIME_MAGIC_MISMATCH'),
  )
})

function createLossGenerator(seed) {
  let state = seed >>> 0
  return () => {
    state = (Math.imul(state, 1_664_525) + 1_013_904_223) >>> 0
    return state / 0x1_0000_0000
  }
}

for (const dropRate of [0.1, 0.2]) {
  test(`${dropRate * 100}% frame loss, duplicates, out-of-order scans, and a mid-cycle start recover exactly`, async () => {
    const original = makeImageBytes('image/png', 48_217)
    const transfer = await prepareOpticalTransfer({
      bytes: original,
      filename: `loss-${dropRate}.png`,
      mimeType: 'image/png',
      sessionId: fixedSession(Math.round(dropRate * 100)),
    })
    const schedule = createLoopingFrameSchedule(transfer, {
      metadataInterval: 8,
    })
    const collector = createOpticalTransferCollector()
    const random = createLossGenerator(0xabc000 + dropRate * 100)
    const startFrame = Math.floor(schedule.framesPerCycle / 2)
    const scanWindow = []
    const maximumFrames = schedule.framesPerCycle * 12

    for (let offset = 0; offset < maximumFrames && !collector.ready; offset += 1) {
      const frame = schedule.getQrPayload(startFrame + offset)
      if (random() >= dropRate) {
        scanWindow.push(frame)
      }

      if (scanWindow.length === 7 || offset === maximumFrames - 1) {
        scanWindow.reverse()
        for (const scannedFrame of scanWindow) {
          const result = collector.ingestQrFrame(scannedFrame)
          if (result.accepted && random() < 0.15) {
            collector.ingestQrFrame(scannedFrame)
          }
        }
        scanWindow.length = 0
      }
    }

    assert.equal(collector.ready, true)
    assert.ok(collector.duplicateCount > 0)
    const result = await collector.assembleAndVerify()
    assert.deepEqual(result.bytes, original)
  })
}
