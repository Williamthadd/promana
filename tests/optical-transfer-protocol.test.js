test('wrong-session frames cannot contaminate an active collector', async () => {
  const [first, second] = await Promise.all([
    prepareOpticalTransfer({
      bytes: makeImageBytes('image/png', 900),
      filename: 'first.png',
      mimeType: 'image/png',
      sessionId: fixedSession(3),
    }),
    prepareOpticalTransfer({
      bytes: makeImageBytes('image/png', 900),
      filename: 'second.png',
      mimeType: 'image/png',
      sessionId: fixedSession(9),
    }),
  ])
  const collector = createOpticalTransferCollector()
  collector.ingestPacket(first.metadataPacket)
  assert.equal(collector.ingestPacket(second.metadataPacket).reason, 'session-mismatch')
  assert.equal(collector.ingestPacket(second.dataPackets[0]).reason, 'session-mismatch')
  assert.equal(collector.getSnapshot().metadata.filename, 'first.png')
  assert.equal(collector.getSnapshot().uniqueChunks, 0)

  const pinned = createOpticalTransferCollector({
    expectedSessionId: first.sessionId,
  })
  assert.equal(pinned.ingestPacket(second.metadataPacket).reason, 'session-mismatch')
})

test('CRC corruption and unsupported versions are rejected', async () => {
  const transfer = await prepareOpticalTransfer({
    bytes: makeImageBytes(),
    filename: 'corruption.png',
    mimeType: 'image/png',
    sessionId: fixedSession(),
  })
  const corrupted = transfer.dataPackets[0].slice()
  corrupted[40] ^= 0xff
  assert.throws(() => deserializePacket(corrupted), expectProtocolCode('CRC_MISMATCH'))

  const futureVersion = transfer.metadataPacket.slice()
  futureVersion[4] = 2
  rewriteChecksum(futureVersion)
  assert.throws(
    () => deserializePacket(futureVersion),
    expectProtocolCode('UNSUPPORTED_VERSION'),
  )
})

test('collector validates chunk indexes, lengths, conflicts, and repeated metadata', async () => {
  const original = makeImageBytes('image/png', 1_201)
  const transfer = await prepareOpticalTransfer({
    bytes: original,
    filename: 'bounds.png',
    mimeType: 'image/png',
    sessionId: fixedSession(),
  })
  const collector = createOpticalTransferCollector()
  collector.ingestPacket(transfer.metadataPacket)

  const badIndex = serializeDataPacket({
    sessionId: transfer.sessionId,
    chunkIndex: transfer.metadata.totalChunks,
    payload: original.subarray(0, 600),
  })
  assert.throws(() => collector.ingestPacket(badIndex), expectProtocolCode('INVALID_CHUNK_INDEX'))

  const shortChunk = serializeDataPacket({
    sessionId: transfer.sessionId,
    chunkIndex: 0,
    payload: original.subarray(0, 599),
  })
  assert.throws(() => collector.ingestPacket(shortChunk), expectProtocolCode('INVALID_CHUNK_LENGTH'))

  collector.ingestPacket(transfer.dataPackets[0])
  const conflictingChunk = serializeDataPacket({
    sessionId: transfer.sessionId,
    chunkIndex: 0,
    payload: Uint8Array.from(original.subarray(0, 600), (byte) => byte ^ 1),
  })
  assert.throws(() => collector.ingestPacket(conflictingChunk), expectProtocolCode('CHUNK_CONFLICT'))

  const otherMetadata = await prepareOpticalTransfer({
    bytes: original,
    filename: 'different-name.png',
    mimeType: 'image/png',
    sessionId: transfer.sessionId,
  })
  assert.throws(
    () => collector.ingestPacket(otherMetadata.metadataPacket),
    expectProtocolCode('METADATA_CONFLICT'),
  )
})

