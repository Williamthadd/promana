import { createHash } from 'node:crypto'
import { existsSync, readFileSync } from 'node:fs'
import path from 'node:path'

const CACHE_PREFIX = 'promana-app-shell'
const PUBLIC_APP_SHELL_FILES = [
  'favicon.svg',
  'logo-proman.png',
  'manifest.webmanifest',
  'offline.html',
  'pwa-icon-192.png',
  'pwa-icon-512.png',
]

function normalizeBase(base = '/') {
  if (!base || base === './') return '/'

  let pathname = base
  if (/^https?:\/\//i.test(base)) {
    pathname = new URL(base).pathname
  }

  pathname = pathname.startsWith('/') ? pathname : `/${pathname}`
  return pathname.endsWith('/') ? pathname : `${pathname}/`
}

function withBase(base, fileName = '') {
  return `${normalizeBase(base)}${String(fileName).replace(/^\/+/, '')}`
}

export function collectPrecacheUrls(bundle, base = '/') {
  const urls = new Set([
    normalizeBase(base),
    withBase(base, 'index.html'),
  ])

  for (const fileName of Object.keys(bundle).sort()) {
    if (fileName === 'sw.js' || fileName.endsWith('.map')) continue
    urls.add(withBase(base, fileName))
  }

  for (const fileName of PUBLIC_APP_SHELL_FILES) {
    urls.add(withBase(base, fileName))
  }

  return [...urls].sort()
}

function hashBuild(bundle, config) {
  const hash = createHash('sha256')

  for (const [fileName, output] of Object.entries(bundle).sort(([left], [right]) =>
    left.localeCompare(right),
  )) {
    if (fileName === 'sw.js' || fileName.endsWith('.map')) continue
    hash.update(fileName)
    hash.update(output.type === 'chunk' ? output.code : output.source)
  }

  const htmlEntryPath = path.join(config.root, 'index.html')
  if (existsSync(htmlEntryPath)) {
    hash.update('index.html')
    hash.update(readFileSync(htmlEntryPath))
  }

  if (config.publicDir) {
    for (const fileName of PUBLIC_APP_SHELL_FILES) {
      const filePath = path.join(config.publicDir, fileName)
      if (existsSync(filePath)) {
        hash.update(fileName)
        hash.update(readFileSync(filePath))
      }
    }
  }

  return hash.digest('hex').slice(0, 16)
}

export function createServiceWorkerSource({
  buildId,
  precacheUrls,
  base = '/',
}) {
  const cacheName = `${CACHE_PREFIX}-${buildId}`
  const appShellUrl = withBase(base, 'index.html')
  const offlineUrl = withBase(base, 'offline.html')

  return `/* Generated by scripts/pwa-app-shell-plugin.js. Do not edit dist/sw.js. */
const CACHE_PREFIX = ${JSON.stringify(`${CACHE_PREFIX}-`)};
const CACHE_NAME = ${JSON.stringify(cacheName)};
const APP_SHELL_URL = ${JSON.stringify(appShellUrl)};
const OFFLINE_URL = ${JSON.stringify(offlineUrl)};
const PRECACHE_URLS = Object.freeze(${JSON.stringify(precacheUrls, null, 2)});
const PRECACHE_PATHS = new Map(
  PRECACHE_URLS.map((url) => [new URL(url, self.location.origin).pathname, url]),
);

self.addEventListener('install', (event) => {
  event.waitUntil((async () => {
    const cache = await caches.open(CACHE_NAME);
    await cache.addAll(
      PRECACHE_URLS.map((url) => new Request(url, { cache: 'reload' })),
    );
  })());
});

self.addEventListener('activate', (event) => {
  event.waitUntil((async () => {
    const cacheNames = await caches.keys();
    await Promise.all(
      cacheNames
        .filter((name) => name.startsWith(CACHE_PREFIX) && name !== CACHE_NAME)
        .map((name) => caches.delete(name)),
    );
    await self.clients.claim();
  })());
});

async function fetchWithTimeout(request, timeoutMs = 3500) {
  const controller = new AbortController();
  const timeoutId = setTimeout(() => controller.abort(), timeoutMs);

  try {
    return await fetch(request, { signal: controller.signal });
  } finally {
    clearTimeout(timeoutId);
  }
}

async function respondToNavigation(request) {
  try {
    return await fetchWithTimeout(request);
  } catch {
    const cache = await caches.open(CACHE_NAME);
    return (
      (await cache.match(APP_SHELL_URL)) ||
      (await cache.match(OFFLINE_URL)) ||
      new Response('ProMana is offline and its app shell is not cached yet.', {
        status: 503,
        headers: { 'Content-Type': 'text/plain; charset=utf-8' },
      })
    );
  }
}

async function respondFromPrecache(request, cacheKey) {
  const cache = await caches.open(CACHE_NAME);
  const cached = await cache.match(cacheKey);
  if (cached) return cached;
  return fetch(request);
}

self.addEventListener('fetch', (event) => {
  const { request } = event;
  if (request.method !== 'GET') return;

  const url = new URL(request.url);
  if (url.origin !== self.location.origin || url.pathname.startsWith('/api/')) {
    return;
  }

  if (request.mode === 'navigate') {
    event.respondWith(respondToNavigation(request));
    return;
  }

  const cacheKey = PRECACHE_PATHS.get(url.pathname);
  if (cacheKey) {
    event.respondWith(respondFromPrecache(request, cacheKey));
  }
});

self.addEventListener('message', (event) => {
  if (event.data?.type === 'SKIP_WAITING') {
    self.skipWaiting();
  }
});
`
}

export function pwaAppShellPlugin() {
  let resolvedConfig

  return {
    name: 'promana-pwa-app-shell',
    apply: 'build',
    configResolved(config) {
      resolvedConfig = config
    },
    generateBundle(_outputOptions, bundle) {
      const base = resolvedConfig?.base || '/'
      const precacheUrls = collectPrecacheUrls(bundle, base)
      const buildId = hashBuild(bundle, resolvedConfig)

      this.emitFile({
        type: 'asset',
        fileName: 'sw.js',
        source: createServiceWorkerSource({ buildId, precacheUrls, base }),
      })
    },
  }
}
